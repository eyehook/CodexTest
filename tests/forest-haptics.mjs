import assert from 'node:assert/strict';
import {plantContact,createContactHaptics} from '../projects/forest/forest-haptics.mjs';
import {SIZE} from '../projects/forest/forest-world.mjs';
const plants=[{x:0,z:0,size:1,kind:0,rotation:0},{x:3,z:0,size:1,kind:3,rotation:0}];
assert.equal(plantContact(plants,{x:0,y:1,z:0}).intensity,.16);
assert.equal(plantContact(plants,{x:SIZE,y:1,z:-SIZE}).id,0);
assert.equal(plantContact(plants,{x:0,y:7,z:0}),null);
assert.equal(plantContact(plants,{x:1,y:1,z:0}),null);
assert.equal(plantContact(plants,{x:3.35,y:.4,z:0}).intensity,.10);
assert.equal(plantContact(plants,{x:3.35,y:2,z:0}),null);
const calls=[],source={gamepad:{hapticActuators:[{pulse:(...args)=>{calls.push(args);return Promise.resolve(true);}}]}};
const h=createContactHaptics(plants),trunk={x:0,y:1,z:0},outside={x:8,y:1,z:0};
h.update(source,trunk,0);assert.deepEqual(calls,[[.16,120]]);
h.update(source,trunk,40);assert.equal(calls.length,1);
h.update(source,trunk,80);assert.equal(calls.length,2);
h.update(source,trunk,160);assert.equal(calls.length,3);
h.update(source,outside,170);assert.deepEqual(calls.at(-1),[0,1]);
h.update(source,outside,180);assert.equal(calls.length,4);
h.update(source,trunk,190);assert.deepEqual(calls.at(-1),[.16,120]);
h.update(source,{x:3.35,y:.4,z:0},200);assert.deepEqual(calls.at(-1),[.10,120]);
h.update(source,null,210);assert.deepEqual(calls.at(-1),[0,1]);
h.update(source,trunk,220);h.reset();assert.deepEqual(calls.at(-1),[0,1]);
h.update(source,trunk,230);h.retain([]);assert.deepEqual(calls.at(-1),[0,1]);
assert.doesNotThrow(()=>h.update({},trunk,500));
assert.doesNotThrow(()=>h.update({gamepad:{hapticActuators:[{pulse:()=>{throw Error('unsupported');}}]}},trunk,500));
h.update({gamepad:{hapticActuators:[{pulse:()=>Promise.reject(Error('rejected'))}]}},trunk,500);
await new Promise(resolve=>setTimeout(resolve,0));
console.log('Wrapped contacts, bush/trunk volumes, sustained gentle pulses, rate limiting, immediate exit/tracking/session/disconnect cancellation, and unsupported/rejected haptics pass.');
